import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {installBrowserEvidence,browserCheckpoint} from './browser-evidence.mjs';
const output=[],logger={log:(...args)=>output.push(['log',...args]),error:(...args)=>output.push(['error',...args])};
const page=new EventEmitter();page.url=()=> 'http://127.0.0.1:1234/pre-alpha/#workspace';page.mainFrame=()=>page;
const context=new EventEmitter();context.pages=()=>[];
const browser=new EventEmitter();browser.newContext=async options=>{assert.equal(options.synthetic,true);return context;};
const evidence=installBrowserEvidence(browser,{engine:'fixture'},logger);
assert.equal(await browser.newContext({synthetic:true}),context);
context.emit('page',page);browserCheckpoint(page,'before assertion');page.emit('framenavigated',page);
page.emit('crash');browser.emit('disconnected');evidence.failure(new Error('original assertion'));
assert.ok(output.some(row=>row[1]==='BROWSER_PAGE_CRASH'));
assert.ok(output.some(row=>row[1]==='BROWSER_UNEXPECTED_DISCONNECT'));
assert.ok(output.some(row=>row[1]==='BROWSER_ORIGINAL_FAILURE'));
for(let n=0;n<80;n++)evidence.mark('bounded-'+n);
assert.equal(evidence.recent().length,60);
const copy=evidence.recent();copy[0].label='changed';assert.notDeepEqual(copy,evidence.recent());
const before=output.length;evidence.closing();browser.emit('disconnected');assert.equal(output.length,before);
assert.equal(evidence.recent().at(-1).expected,true);
page.url=()=> 'https://private.example.invalid/secret';browserCheckpoint(page,'no external address');
assert.equal(evidence.recent().at(-1).url,'<non-fixture URL>');
assert.ok(!JSON.stringify(output).includes('private.example'));
console.log('PASS bounded browser evidence: checkpoints, original failures, crashes/unexpected disconnects, expected teardown, immutable ring and non-fixture URL redaction');
