    await waitForWorkspaceSave(page);
    const before=await readWorkspaceSnapshot(page),saved=before.jobs.find(job=>job.id===before.activeId);
    assert.deepEqual(saved.original.record,history[74].record);
    assert.deepEqual(saved.operations[1].state,history[74].record.jobBundle.operations[1].state);
    assert.deepEqual(saved.operations[0].state.unknownFuture,{keep:[1,2,3]});
