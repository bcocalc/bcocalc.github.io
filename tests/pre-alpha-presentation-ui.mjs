    await waitForWorkspaceSave(page);
    const after=await readWorkspaceSnapshot(page);
    assert.deepEqual(after.jobs,before.jobs,'Presentation and reload must preserve complete saved bundles');
    await activate(page.locator('[data-step="tap"]'));
    assert.match(await page.locator('[data-value-origin="md"]').textContent(),/Origin unrecorded/,'Session provenance must not masquerade as recorded history after reload');
